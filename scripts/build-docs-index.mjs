#!/usr/bin/env node
/**
 * Build-time docs indexer for the AI Mentor RAG layer.
 *
 * Reads all docs/*.md files, splits them into sections by markdown headers,
 * extracts keywords for each section, and writes a TypeScript module that
 * knowledge-base.ts imports at runtime. This keeps the mentor's knowledge
 * auto-current with the docs — no manual KB updates needed for documented features.
 *
 * Usage: node scripts/build-docs-index.mjs
 * Output: apps/applicant/data/docs-index.ts
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, basename } from "node:path";

const DOCS_DIR = join(process.cwd(), "docs");
const OUT_DIR = join(process.cwd(), "apps", "applicant", "data");
const OUT_FILE = join(OUT_DIR, "docs-index.ts");

const STOP_WORDS = new Set([
  "the", "a", "an", "is", "are", "was", "were", "be", "been", "being", "have", "has", "had",
  "do", "does", "did", "will", "would", "could", "should", "may", "might", "must", "can",
  "of", "in", "on", "at", "to", "for", "with", "by", "from", "as", "and", "or", "not", "no",
  "but", "if", "then", "else", "this", "that", "these", "those", "it", "its", "they", "them",
  "their", "there", "here", "which", "who", "whom", "whose", "what", "when", "where", "why",
  "how", "all", "any", "each", "every", "some", "none", "both", "either", "neither", "per",
  "via", "etc", "you", "your", "we", "our", "us", "i", "me", "my", "so", "than", "also",
  "into", "out", "up", "down", "over", "under", "more", "most", "such", "only", "own", "same",
]);

const MAX_SECTION_CHARS = 2500;
const MAX_SECTIONS = 400;

/** Extract meaningful keywords from text (lowercase, >3 chars, not stop words). */
function extractKeywords(text) {
  const words = text.toLowerCase().match(/[a-z][a-z0-9-]{2,30}/g) ?? [];
  const freq = new Map();
  for (const w of words) {
    if (STOP_WORDS.has(w)) continue;
    freq.set(w, (freq.get(w) ?? 0) + 1);
  }
  // Sort by frequency, take top 12
  return [...freq.entries()]
    .sort((a, b) => b[1] - a[1])
    .slice(0, 12)
    .map(([w]) => w);
}

/** Split a markdown file into sections by ## and # headers. */
function splitIntoSections(content, source) {
  const lines = content.split("\n");
  const sections = [];
  let currentTitle = basename(source, ".md").replace(/[-_]/g, " ");
  let currentBody = [];

  function flush() {
    const body = currentBody.join("\n").trim();
    if (body.length < 30) return;
    const title = currentTitle.trim();
    const keywords = extractKeywords(title + " " + body.slice(0, 500));
    if (keywords.length === 0) return;
    sections.push({
      title,
      source,
      content: body.slice(0, MAX_SECTION_CHARS),
      keywords,
    });
  }

  for (const line of lines) {
    const h2 = line.match(/^##\s+(.+)/);
    const h1 = line.match(/^#\s+(.+)/);
    if (h2 || h1) {
      flush();
      currentTitle = (h2 ? h2[1] : h1[1]).trim();
      currentBody = [];
    } else {
      currentBody.push(line);
    }
  }
  flush();
  return sections;
}

// --- Main ---
if (!existsSync(DOCS_DIR)) {
  console.error("[docs-index] docs/ directory not found, skipping.");
  process.exit(0);
}

const mdFiles = readdirSync(DOCS_DIR).filter((f) => f.endsWith(".md"));
let allSections = [];

for (const file of mdFiles) {
  const source = `docs/${file}`;
  try {
    const content = readFileSync(join(DOCS_DIR, file), "utf-8");
    const sections = splitIntoSections(content, source);
    allSections.push(...sections);
  } catch (err) {
    console.warn(`[docs-index] Could not read ${source}: ${err.message}`);
  }
}

// Cap total sections to keep the bundle reasonable
if (allSections.length > MAX_SECTIONS) {
  allSections = allSections.slice(0, MAX_SECTIONS);
}

if (!existsSync(OUT_DIR)) {
  mkdirSync(OUT_DIR, { recursive: true });
}

const ts = `// AUTO-GENERATED by scripts/build-docs-index.mjs — do not edit manually.
// Regenerate with: npm run build:docs-index
// Source: docs/*.md | Sections: ${allSections.length} | Generated: ${new Date().toISOString()}

export type DocsIndexEntry = {
  title: string;
  source: string;
  content: string;
  keywords: string[];
};

export const docsIndex: DocsIndexEntry[] = ${JSON.stringify(allSections, null, 0)};
`;

writeFileSync(OUT_FILE, ts, "utf-8");
console.log(`[docs-index] Indexed ${mdFiles.length} docs files → ${allSections.length} sections → ${OUT_FILE}`);
